"""
Rasterize a TTF into a 1-bit proportional bitmap font header for the OLED driver.

    python ttf2font.py Poppins-Medium.ttf 10 body   > font_body.h
    python ttf2font.py Poppins-Bold.ttf   11 title  > font_title.h

Header format (all const, lives in flash):
    typedef struct { uint8_t height, line_height, space, *glyph_w...
    glyph data: column-major, ceil(height/8) bytes per column, bit0 = top row
Threshold is applied to the anti-aliased raster; tune --thresh if strokes look thin/heavy.
"""
import sys, argparse
from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument("ttf"); ap.add_argument("px", type=int); ap.add_argument("name")
ap.add_argument("--thresh", type=int, default=110)
ap.add_argument("--tracking", type=int, default=1, help="extra pixels after each glyph")
a = ap.parse_args()

font = ImageFont.truetype(a.ttf, a.px)
ascent, descent = font.getmetrics()
# Find the actual ink extent over printable ASCII so we don't waste rows on empty leading.
top, bottom = 99, -99
rasters = {}
for code in range(32, 127):
    ch = chr(code)
    w = max(1, int(round(font.getlength(ch))))
    img = Image.new("L", (w + 4, ascent + descent + 2), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    bw = img.point(lambda p: 255 if p > a.thresh else 0)
    bbox = bw.getbbox()
    rasters[code] = (bw, w)
    if bbox:
        top = min(top, bbox[1]); bottom = max(bottom, bbox[3])
height = bottom - top
bpc = (height + 7) // 8                                   # bytes per column

out = [f"// Generated by ttf2font.py from {a.ttf} at {a.px}px. Font under its own license (Poppins: SIL OFL).",
       "#pragma once", "#include <stdint.h>",
       f"#define FONT_{a.name.upper()}_HEIGHT {height}",
       f"static const uint8_t font_{a.name}_w[95] = {{"]
widths, data, offsets = [], [], []
for code in range(32, 127):
    bw, adv = rasters[code]
    bbox = bw.getbbox()
    if code == 32 or not bbox:                             # space: advance only
        gw = max(2, a.px // 3)
        cols = [[0] * bpc for _ in range(gw)]
        x0 = 0
    else:
        x0, x1 = bbox[0], bbox[2]
        gw = x1 - x0
        px = bw.load()
        cols = []
        for x in range(x0, x1):
            col = [0] * bpc
            for y in range(height):
                if px[x, top + y]: col[y // 8] |= 1 << (y % 8)
            cols.append(col)
    offsets.append(len(data) // bpc)
    widths.append(gw)
    for col in cols: data.extend(col)
out.append(",".join(str(w) for w in widths) + "};")
out.append(f"static const uint16_t font_{a.name}_off[95] = {{" + ",".join(map(str, offsets)) + "};")
out.append(f"static const uint8_t font_{a.name}_data[{len(data)}] = {{")
for i in range(0, len(data), 24):
    out.append(",".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
out.append("};")
out.append(f"static const font_t font_{a.name} = {{ {height}, {bpc}, {a.tracking}, font_{a.name}_w, font_{a.name}_off, font_{a.name}_data }};")
print("\n".join(out))
print(f"// {len(data)} bytes of glyph data, height {height}px", file=sys.stderr)
